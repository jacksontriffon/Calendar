/**
 * Hashing for the phone-calendar bridge. Pure TypeScript (SHA-256), so it works the same on Hermes,
 * web and jest, with no native module.
 *
 * Two uses, both about keeping phone data off the server:
 *  - `hiddenKey`: the opaque `hidden_items.external_key` for a phone event. The server only ever sees a
 *    digest of the calendar id and event id, never the ids, titles or times themselves.
 *  - fingerprints of OUR events that are published to a phone calendar (change detection).
 */

